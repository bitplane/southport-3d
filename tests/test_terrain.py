def synthetic(tmp_path):
    tiles = {}
    # Analytic plane z = 2 + .1 E + .2 N, spanning four tile boundaries.
    for west in [0, 4]:
        for south in [0, 4]:
            e, n = np.meshgrid(np.arange(4)+west+.5, south+4-np.arange(4)-.5)
            name = f'{west}_{south}.npz'
            np.savez_compressed(tmp_path/name, odn_mm=np.rint(1000*(2+.1*e+.2*n)).astype(np.int16), valid=np.ones((4, 4), dtype=bool))
            tiles[f'{west}_{south}'] = {'path': name}
    path = tmp_path/'terrain.json'
    path.write_text(json.dumps({'schema_version': 1, 'crs': 'EPSG:27700',
                               'site_xy_to_bng_affine': [[1, 0], [0, 1], [0, 0]],
                               'local_zero_odn_m': 2, 'tile_size_m': 4, 'resolution_m': 1, 'tiles': tiles}))
    return Terrain(path)


def test_pixel_centres_and_four_tile_intersection(tmp_path):
    t = synthetic(tmp_path)
    for x, y in [(1.5, 2.5), (3.999, 4.001), (4, 4), (4.001, 3.999), (.5, .5), (7.5, 7.5)]:
        assert t.height_odn(x, y) == pytest.approx(2+.1*x+.2*y, abs=1e-10)
        assert t.height(x, y) == pytest.approx(.1*x+.2*y, abs=1e-10)


