def test_mesh_splits_at_height_grid_and_preserves_ownership_area(tmp_path):
    t = synthetic(tmp_path)
    s = SurveySurface(t.path, 'test', [1, 7, 1, 7], grid_m=2)
    # Non-planar field ensures a test cannot pass by only lifting endpoints.
    s.node = lambda i, j: float((i % 2)*2+(j % 3))
    original = [(1, 1), (7, 1), (3, 7)]
    lifted = list(s.lift_triangle(original))
    assert sum(area([p[:2] for p in tri]) for tri in lifted) == pytest.approx(area(original))
    assert len(lifted) > 10
    for tri in lifted:
        p = np.mean(tri, axis=0)
        assert p[2] == pytest.approx(s.height(*p[:2]), abs=1e-10)
    points = list(s.edge_points((1, 1), (7, 5)))
    for a, b in zip(points, points[1:]):
        centre = (np.array(a)+np.array(b))/2
        assert centre[2] == pytest.approx(s.height(*centre[:2]), abs=1e-10)


